use coppervox_analyzer::{
    QuadsReader,
    block_mesh::{QuadBuffer, QuadCoordinateConfig},
};
use macroquad::{
    math::{Vec2, Vec3, Vec4},
    models::Mesh,
    ui::Vertex,
};
use std::sync::Arc;

/// Read the quad data to generate a mesh
pub struct QuadDataReader {
    /// Flag indicating if UVs should be flipped vertically
    uv_flip_v: bool,
}

impl QuadDataReader {
    /// Create a quad reader to generate meshes
    #[inline]
    pub fn new(uv_flip_v: bool) -> Self {
        Self { uv_flip_v }
    }
}

impl QuadsReader<Arc<Mesh>> for QuadDataReader {
    /// Read the data generated by block_mesh and build a mesh usable by macroquad
    fn read_quads(&mut self, quads: &QuadBuffer, config: &QuadCoordinateConfig) -> Arc<Mesh> {
        let count = quads.num_quads();
        let mut indices = Vec::<u16>::with_capacity(count * 6);
        let mut vertices = Vec::<Vertex>::with_capacity(count * 4);

        // iterate over all of the quads to build mesh data
        for (group, face) in quads.groups.iter().zip(&config.faces) {
            for (i, quad) in group.iter().enumerate() {
                // store indices for the quad
                indices.extend_from_slice(
                    face.quad_mesh_indices((i * 4) as u32)
                        .map(|i| i as u16)
                        .as_slice(),
                );

                // store the vertices of the quads
                let positions = face.quad_mesh_positions(quad, 1.0);
                let normals = face.quad_mesh_normals();
                let uvs = face.tex_coords(config.u_flip_face, self.uv_flip_v, quad);

                // Combine positions, normals and UVs into a vertices
                for (pos, (norm, uv)) in positions.iter().zip(normals.iter().zip(uvs.iter())) {
                    // Build a macroquad vertex from the provided data
                    vertices.push(Vertex {
                        position: Vec3::from_array(*pos),
                        uv: Vec2::from_array(*uv),
                        color: [0xff, 0xff, 0xff, 0xff],
                        normal: Vec4::new(norm[0], norm[1], norm[2], 0.0),
                    });
                }
            }
        }

        // Build the mesh
        Arc::new(Mesh {
            vertices,
            indices,
            texture: None,
        })
    }
}
