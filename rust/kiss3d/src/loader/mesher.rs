use coppervox_analyzer::{
    QuadsReader,
    block_mesh::{QuadBuffer, QuadCoordinateConfig},
};
use kiss3d::{
    glamx::{Vec2, Vec3},
    procedural::{IndexBuffer, RenderMesh},
};
use std::sync::Arc;

// Mesh type expected by Kiss3D
//pub type Mesh = Rc<RefCell<GpuMesh3d>>;

/// Read the quad data to generate a mesh
pub struct QuadDataReader {
    /// Flag indicating if we should compute UV coordinates
    use_uvs: bool,

    /// Flag indicating if UVs should be flipped vertically
    uv_flip_v: bool,
}

impl QuadDataReader {
    /// Create a quad reader to generate meshes
    #[inline]
    pub fn new(use_uvs: bool, uv_flip_v: bool) -> Self {
        Self { use_uvs, uv_flip_v }
    }
}

impl QuadsReader<Arc<RenderMesh>> for QuadDataReader {
    /// Read the data generated by block_mesh and build a mesh usable by macroquad
    fn read_quads(&mut self, quads: &QuadBuffer, config: &QuadCoordinateConfig) -> Arc<RenderMesh> {
        let count = quads.num_quads();
        let vertex_count = count * 4;

        // allocate buffers to store the mesh data
        let mut coords = Vec::<Vec3>::with_capacity(vertex_count);
        let mut normals = Vec::<Vec3>::with_capacity(vertex_count);
        let mut uvs = Vec::<Vec2>::with_capacity(vertex_count);
        let mut indices = Vec::<[u32; 3]>::with_capacity(count * 2);

        // iterate over all of the quads to build mesh data
        for (group, face) in quads.groups.iter().zip(&config.faces) {
            for (i, quad) in group.iter().enumerate() {
                // Add the indices to compose the two triangles
                let [t0, t1, t2, t3, t4, t5] = face.quad_mesh_indices(i as u32 * 4);
                indices.push([t0, t1, t2]);
                indices.push([t3, t4, t5]);

                // store the vertices of the quad
                for &coord in face.quad_mesh_positions(quad, 1.0).iter() {
                    coords.push(Vec3::from(coord));
                }
                for &normal in face.quad_mesh_normals().iter() {
                    normals.push(Vec3::from(normal));
                }
                for &uv in face
                    .tex_coords(config.u_flip_face, self.uv_flip_v, quad)
                    .iter()
                {
                    uvs.push(Vec2::from(uv));
                }
            }
        }

        // Build the mesh
        Arc::new(RenderMesh::new(
            coords,
            Some(normals),
            Some(uvs),
            Some(IndexBuffer::Unified(indices)),
        ))
    }
}
