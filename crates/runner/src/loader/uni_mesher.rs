use coppervox_analyzer::{
    QuadsReader,
    block_mesh::{
        QuadBuffer, QuadCoordinateConfig,
        ilattice::glam::{IVec3, UVec3},
    },
};
use kiss3d::{
    glamx::{Vec2, Vec3},
    procedural::{IndexBuffer, RenderMesh},
};
use std::rc::Rc;

/*
 * We want to group all components into a single large mesh.
 * Coordinates and normals can be grouped into a single buffer.
 * For each mesh generated, we want to return a list of indexes.
 * This list will be used to populate an global array of indexes.
 * This way we can render all components with a single mesh while
 * staying into Kiss3D framework.
 */

/// The four possible sides
const SIDES: usize = 6;

/// Read the quad data to generate a mesh
pub struct UniQuadDataReader {
    /// position of the vertices in 3D space
    pub coords: Vec<UVec3>,

    /// normals of the vertices (we have six possible values)
    pub normals: [IVec3; SIDES],

    /// Count the number of meshes that have been generated
    pub mesh_count: usize,
}

/// Store the indices to retrieve the mesh data that was collected
#[derive(Debug)]
pub struct MeshIndices {
    /// Indices of the vertex data that was added to the `coords` buffer
    pub indices: Vec<([u32; 6], u32)>,

    /// Index of the mesh that have been generated
    pub mesh_index: usize,
}

impl UniQuadDataReader {
    /// Create a quad reader to generate meshes
    #[inline]
    pub fn new(vert_count: usize) -> Self {
        Self {
            coords: Vec::with_capacity(vert_count),
            normals: [IVec3::default(); SIDES],
            mesh_count: 0,
        }
    }

    /// Create the normal buffer
    pub fn read_normals(&mut self, config: &QuadCoordinateConfig) {
        for (face, norm) in config.faces.iter().zip(self.normals.iter_mut()) {
            *norm = face.signed_normal();
        }
    }

    /// Convert the read data into a single render mesh
    pub fn to_mesh(&self, indices: Vec<[[u32; 3]; 3]>, extra: Vec<[u32; 2]>) -> Rc<RenderMesh> {
        // Compose coordinates buffer
        let coords = self
            .coords
            .iter()
            .map(|c| {
                let [x, y, z] = c.to_array();
                Vec3::new(x as f32, y as f32, z as f32)
            })
            .collect();

        // Compose normal buffer
        let normals = self
            .normals
            .iter()
            .map(|n| {
                let [x, y, z] = n.to_array();
                Vec3::new(x as f32, y as f32, z as f32)
            })
            .collect();

        // Compose UV buffer but hack in the extra data buffer
        let uvs = extra
            .iter()
            .map(|[u, v]| Vec2::new(f32::from_bits(*u), f32::from_bits(*v)))
            .collect();

        // Generate a mesh for Kiss3D
        Rc::new(RenderMesh::new(
            coords,
            Some(normals),
            Some(uvs),
            Some(IndexBuffer::Split(indices)),
        ))
    }
}

impl QuadsReader<MeshIndices> for UniQuadDataReader {
    /// Read the data generated by block_mesh and collect new vertex data
    fn read_quads(&mut self, quads: &QuadBuffer, config: &QuadCoordinateConfig) -> MeshIndices {
        // Allocate a buffer to store indexes
        let count = quads
            .groups
            .iter()
            .fold(0usize, |acc, quads| acc + quads.len());
        let mut indices = Vec::with_capacity(count);

        // mesh index
        let mesh_index = self.mesh_count;
        self.mesh_count += 1;

        // iterate over all of the quads to build mesh data
        for (index, (group, face)) in quads.groups.iter().zip(&config.faces).enumerate() {
            // For each 3D coordinates, check if it has already been added to the buffer,
            // in that case recover the index otherwise add the new coordinate.

            // index of the normal to use
            let norm = index as u32;

            // Let block mesh resolve the winding order
            let [i0, i1, i2, i3, i4, i5] = face.quad_mesh_indices(0);

            // Keep track of the indexes of the 3D points as defined in the global `coords` buffer
            let mut coord_indexes = [0u32; 4];
            for quad in group.iter() {
                for (i, &coord) in face.quad_corners(quad).iter().enumerate() {
                    // Get the index of the 3D point in the `coords` buffer
                    if let Some(pos) = self.coords.iter().position(|&c| c == coord) {
                        coord_indexes[i] = pos as u32;
                    } else {
                        coord_indexes[i] = self.coords.len() as u32;
                        self.coords.push(coord);
                    }
                }

                // resove the indexes of the point in the global buffer
                let t0 = coord_indexes[i0 as usize];
                let t1 = coord_indexes[i1 as usize];
                let t2 = coord_indexes[i2 as usize];
                let t3 = coord_indexes[i3 as usize];
                let t4 = coord_indexes[i4 as usize];
                let t5 = coord_indexes[i5 as usize];

                // Add the indices to compose the two triangles
                indices.push(([t0, t1, t2, t3, t4, t5], norm));
            }
        }

        // Return the index where we inserted the mesh data
        MeshIndices {
            indices,
            mesh_index,
        }
    }
}

impl MeshIndices {
    /// Compose the `indices` buffer by pushing from this buffer
    pub fn push_to(
        &self,
        comp_index: usize,
        indices: &mut Vec<[[u32; 3]; 3]>,
        extra: &mut Vec<[u32; 2]>,
    ) {
        // convert the index buffer into a format supported by Kiss3D
        let id = comp_index as u32;
        for &([i0, i1, i2, i3, i4, i5], norm) in self.indices.iter() {
            indices.push([[i0, norm, id], [i1, norm, id], [i2, norm, id]]);
            indices.push([[i3, norm, id], [i4, norm, id], [i5, norm, id]]);
        }

        // store component index into extra buffer
        extra.push([id, id]);
    }
}
