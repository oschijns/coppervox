use coppervox_analyzer::{
    analyzer::QuadsReader,
    block_mesh::{QuadBuffer, QuadCoordinateConfig},
};
use godot::{
    builtin::{
        PackedInt32Array, PackedVector2Array, PackedVector3Array, Variant, VariantArray, Vector2,
        Vector3,
    },
    classes::{
        ArrayMesh,
        mesh::{ArrayType, PrimitiveType},
    },
    meta::ToGodot,
    obj::{EngineEnum, Gd, NewGd},
};

/// Read block_mesh data to build a Mesh usable with Godot
pub struct Mesher {
    /// Indices defining triangles
    indices: Vec<i32>,

    /// positions of the vertices
    positions: Vec<Vector3>,

    /// normals of the vertices
    normals: Vec<Vector3>,

    /// UV coordinates of the vertices
    uvs: Vec<Vector2>,

    /// Flag indicating if we should compute UV coordinates
    use_uvs: bool,

    /// Flag indicating if UVs should be flipped vertically
    uv_flip_v: bool,
}

impl Mesher {
    /// Create a mesher without UV coordinates generation
    #[inline]
    pub fn new(quad_count: usize) -> Self {
        Self::new_with_uvs(quad_count, false, false)
    }

    /// Create a mesher with UV coordinates generation
    #[inline]
    pub fn new_with_uvs(quad_count: usize, use_uvs: bool, uv_flip_v: bool) -> Self {
        let vert_count = quad_count * 4;
        Self {
            indices: Vec::with_capacity(quad_count * 6),
            positions: Vec::with_capacity(vert_count),
            normals: Vec::with_capacity(vert_count),
            uvs: Vec::with_capacity(vert_count),
            use_uvs,
            uv_flip_v,
        }
    }
}

impl QuadsReader<Gd<ArrayMesh>> for Mesher {
    /// Read the data generated by block_mesh and build a mesh usable by Godot
    fn read_quads(&mut self, quads: &QuadBuffer, config: &QuadCoordinateConfig) -> Gd<ArrayMesh> {
        // Prepare arrays to store the vertices data
        self.indices.clear();
        self.positions.clear();
        self.normals.clear();
        self.uvs.clear();

        // iterate over all of the quads to build mesh data
        for (group, face) in quads.groups.iter().zip(&config.faces) {
            for (i, quad) in group.iter().enumerate() {
                // store indices for the quad
                self.indices.extend_from_slice(
                    face.quad_mesh_indices((i * 4) as u32)
                        .map(|i| i as i32)
                        .as_slice(),
                );

                // store the positions of the quads
                self.positions.extend_from_slice(
                    face.quad_mesh_positions(quad, 1.0)
                        .map(|v| Vector3::from_array(v))
                        .as_slice(),
                );

                // store the normals of the quads
                self.normals.extend_from_slice(
                    face.quad_mesh_normals()
                        .map(|v| Vector3::from_array(v))
                        .as_slice(),
                );

                if self.use_uvs {
                    // store the UV coordinates of the quads
                    self.uvs.extend_from_slice(
                        face.tex_coords(config.u_flip_face, self.uv_flip_v, quad)
                            .map(|v| Vector2::from_array(v))
                            .as_slice(),
                    );
                }
            }
        }

        // group the generated arrays to be passed to Godot
        let mut arrays = VariantArray::new();
        arrays.resize(ArrayType::MAX.ord() as usize, &Variant::nil());

        // convert the arrays into ones supported by Godot
        macro_rules! set {
            ([$index:ident] = $array:ident as $type:ty) => {
                arrays.set(
                    ArrayType::$index.ord() as usize,
                    &<$type>::from(self.$array.as_slice()).to_variant(),
                );
            };
        }
        set! { [INDEX]  = indices   as PackedInt32Array   }
        set! { [VERTEX] = positions as PackedVector3Array }
        set! { [NORMAL] = normals   as PackedVector3Array }
        if self.use_uvs {
            set! {[TEX_UV] = uvs as PackedVector2Array }
        }

        // Create a new ArrayMesh to return
        let mut array_mesh = ArrayMesh::new_gd();
        array_mesh.add_surface_from_arrays(PrimitiveType::TRIANGLES, &arrays);
        array_mesh
    }
}
